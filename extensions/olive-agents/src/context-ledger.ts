/**
 * context-ledger.ts — Durable, user-selected context that accompanies an agent
 * launch, plus the persisted graph that /ot reconstructs from session files.
 *
 * Ledger model:
 *   - Every agent launch that builds context emits a ContextLedgerNode. The
 *     node is stored ONCE, in the CHILD session's JSONL, as a pi custom entry
 *     (`olive-agent-context-ledger`). It carries snapshots (not just entry
 *     ids), so it survives compaction / branching of the source session.
 *   - The PARENT session stores a link entry (`olive-agent-context-link`) that
 *     records the child session identity + reopen descriptor + ledger ids.
 *   - Context inheritance follows `node.parentId`, NOT session nesting, so
 *     parallel children, skipped-parent children, and isolated launches all
 *     place correctly in the /ot tree.
 *   - The child's launch prompt carries the FULL inherited chain (ancestor
 *     nodes root→leaf + the new node), so a fresh agent sees its whole
 *     upstream context without re-reading any session file.
 *
 * Nothing here writes to the project workspace. Ledger persistence uses pi
 * session JSONL files only; temporary launch specs use the existing
 * /tmp/olive-agents mailbox dirs.
 */

